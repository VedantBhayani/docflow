"""Synthetic GST tax invoices with ground truth.

The truth file records every Field exactly as printed, so extraction accuracy is
measured against what is on the page, not against an idealised value.
"""

import json
import random
from dataclasses import dataclass, field
from datetime import date, timedelta
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas

from docflow.synth.common import CATALOGUE, STATES, Party, fmt_inr, make_party, money

POST_REFORM_SLABS = [Decimal("5"), Decimal("18"), Decimal("40")]  # from 22.09.2025 (research 01, section E)
SYNTHETIC_FOOTER = "SYNTHETIC TEST DOCUMENT - generated by DocFlow, not a real invoice"


@dataclass
class Line:
    description: str
    hsn: str
    qty: Decimal
    uqc: str
    unit_price: Decimal
    gst_rate: Decimal
    taxable: Decimal = Decimal(0)
    cgst: Decimal = Decimal(0)
    sgst: Decimal = Decimal(0)
    igst: Decimal = Decimal(0)


@dataclass
class InvoiceSpec:
    supplier: Party
    recipient: Party
    invoice_no: str
    invoice_date: date
    pos_code: str
    reverse_charge: str
    lines: list[Line]
    intra_state: bool = field(init=False)
    taxable_total: Decimal = Decimal(0)
    cgst_total: Decimal = Decimal(0)
    sgst_total: Decimal = Decimal(0)
    igst_total: Decimal = Decimal(0)
    round_off: Decimal = Decimal(0)
    grand_total: Decimal = Decimal(0)

    def __post_init__(self):
        self.intra_state = self.supplier.state_code == self.pos_code
        self.compute()

    def compute(self):
        """GST arithmetic as invoicing software does it: per-line tax, rupee round-off on the total."""
        for ln in self.lines:
            ln.taxable = money(ln.qty * ln.unit_price)
            if self.intra_state:
                ln.cgst = money(ln.taxable * ln.gst_rate / 200)
                ln.sgst = money(ln.taxable * ln.gst_rate / 200)
                ln.igst = Decimal("0.00")
            else:
                ln.cgst = ln.sgst = Decimal("0.00")
                ln.igst = money(ln.taxable * ln.gst_rate / 100)
        self.taxable_total = sum((ln.taxable for ln in self.lines), Decimal("0.00"))
        self.cgst_total = sum((ln.cgst for ln in self.lines), Decimal("0.00"))
        self.sgst_total = sum((ln.sgst for ln in self.lines), Decimal("0.00"))
        self.igst_total = sum((ln.igst for ln in self.lines), Decimal("0.00"))
        pre_round = self.taxable_total + self.cgst_total + self.sgst_total + self.igst_total
        self.grand_total = pre_round.quantize(Decimal("1"), rounding=ROUND_HALF_UP).quantize(Decimal("0.01"))
        self.round_off = self.grand_total - pre_round


def build_spec(rng: random.Random, serial: int, invoice_date: date | None = None, intra_state: bool | None = None, n_lines: int | None = None) -> InvoiceSpec:
    supplier_state = rng.choice(list(STATES))
    if intra_state is None:
        intra_state = rng.random() < 0.5
    recipient_state = supplier_state if intra_state else rng.choice([s for s in STATES if s != supplier_state])
    supplier = make_party(rng, supplier_state)
    recipient = make_party(rng, recipient_state)
    invoice_date = invoice_date or date(2026, 4, 1) + timedelta(days=rng.randint(0, 190))
    fy = f"{invoice_date.year % 100:02d}{invoice_date.year % 100 + 1:02d}" if invoice_date.month >= 4 else f"{invoice_date.year % 100 - 1:02d}{invoice_date.year % 100:02d}"
    lines = []
    for desc, hsn, uqc, price in rng.sample(CATALOGUE, n_lines or rng.randint(1, 5)):
        qty = Decimal(rng.choice([1, 2, 3, 5, 10, 12, 25, 40, 100])) if uqc != "OTH" else Decimal(1)
        unit_price = money(Decimal(price) * Decimal(rng.uniform(0.85, 1.2)))
        lines.append(Line(desc, hsn, qty, uqc, unit_price, rng.choice(POST_REFORM_SLABS[:2])))
    return InvoiceSpec(
        supplier=supplier,
        recipient=recipient,
        invoice_no=f"DFTEST-{fy}-{serial:04d}",
        invoice_date=invoice_date,
        pos_code=recipient_state,
        reverse_charge="No",
        lines=lines,
    )


def _qty(q: Decimal) -> str:
    return f"{q:.2f}".rstrip("0").rstrip(".")


def _pct(r: Decimal) -> str:
    return f"{_qty(r)}%"


def truth_tally(spec: InvoiceSpec) -> dict:
    """Every Field exactly as the 'tally' template prints it."""
    zero = lambda x: fmt_inr(x)  # noqa: E731 - template prints 0.00 explicitly
    return {
        "kind": "invoice",
        "template": "tally",
        "fields": {
            "supplier_name": spec.supplier.name,
            "supplier_address": spec.supplier.address,
            "supplier_gstin": spec.supplier.gstin,
            "recipient_name": spec.recipient.name,
            "recipient_address": spec.recipient.address,
            "recipient_gstin": spec.recipient.gstin,
            "invoice_no": spec.invoice_no,
            "invoice_date": spec.invoice_date.strftime("%d/%m/%Y"),
            "place_of_supply": f"{STATES[spec.pos_code]} ({spec.pos_code})",
            "reverse_charge": spec.reverse_charge,
            "taxable_total": fmt_inr(spec.taxable_total),
            "cgst_total": zero(spec.cgst_total),
            "sgst_total": zero(spec.sgst_total),
            "igst_total": zero(spec.igst_total),
            "round_off": fmt_inr(spec.round_off),
            "grand_total": fmt_inr(spec.grand_total),
        },
        "lines": [
            {
                "description": ln.description,
                "hsn": ln.hsn,
                "qty": _qty(ln.qty),
                "uqc": ln.uqc,
                "unit_price": fmt_inr(ln.unit_price),
                "taxable_value": fmt_inr(ln.taxable),
                "gst_rate": _pct(ln.gst_rate),
                "cgst": zero(ln.cgst),
                "sgst": zero(ln.sgst),
                "igst": zero(ln.igst),
            }
            for ln in spec.lines
        ],
        "expected_flags": [],
    }


def render_tally(spec: InvoiceSpec, path: Path) -> dict:
    """Tally-style A4 invoice. Returns the truth dict for exactly what was drawn."""
    t = truth_tally(spec)
    f, lines = t["fields"], t["lines"]
    W, H = A4
    c = canvas.Canvas(str(path), pagesize=A4, invariant=1)  # byte-deterministic output
    c.setTitle(f"Tax Invoice {spec.invoice_no} (SYNTHETIC)")

    c.setFont("Helvetica-Bold", 15)
    c.drawCentredString(W / 2, H - 40, "TAX INVOICE")
    y = H - 70
    c.setFont("Helvetica-Bold", 11)
    c.drawString(36, y, f["supplier_name"])
    c.setFont("Helvetica", 8.5)
    c.drawString(36, y - 13, f["supplier_address"])
    c.drawString(36, y - 26, f"GSTIN: {f['supplier_gstin']}")
    c.drawString(36, y - 39, f"State: {STATES[spec.supplier.state_code]} ({spec.supplier.state_code})")

    rx = 360
    c.drawString(rx, y, f"Invoice No.: {f['invoice_no']}")
    c.drawString(rx, y - 13, f"Invoice Date: {f['invoice_date']}")
    c.drawString(rx, y - 26, f"Place of Supply: {f['place_of_supply']}")
    c.drawString(rx, y - 39, f"Reverse Charge: {f['reverse_charge']}")

    y -= 70
    c.setFont("Helvetica-Bold", 9)
    c.drawString(36, y, "Bill To:")
    c.setFont("Helvetica", 8.5)
    c.drawString(36, y - 13, f["recipient_name"])
    c.drawString(36, y - 26, f["recipient_address"])
    c.drawString(36, y - 39, f"GSTIN: {f['recipient_gstin']}")

    # Line-item table
    y -= 70
    cols = [("Sl", 36), ("Description", 52), ("HSN/SAC", 200), ("Qty", 248), ("Unit", 276), ("Rate", 304),
            ("Taxable Value", 352), ("GST %", 416), ("CGST", 448), ("SGST", 494), ("IGST", 540)]
    c.setFont("Helvetica-Bold", 7.5)
    for name, x in cols:
        c.drawString(x, y, name)
    c.line(36, y - 4, W - 30, y - 4)
    c.setFont("Helvetica", 7.5)
    for i, ln in enumerate(lines, 1):
        y -= 16
        values = [str(i), ln["description"], ln["hsn"], ln["qty"], ln["uqc"], ln["unit_price"],
                  ln["taxable_value"], ln["gst_rate"], ln["cgst"], ln["sgst"], ln["igst"]]
        for (_, x), v in zip(cols, values):
            c.drawString(x, y, v)
    c.line(36, y - 6, W - 30, y - 6)

    # Totals
    y -= 30
    for label, key in [("Taxable Value", "taxable_total"), ("CGST", "cgst_total"), ("SGST", "sgst_total"),
                       ("IGST", "igst_total"), ("Round Off", "round_off"), ("Grand Total", "grand_total")]:
        c.setFont("Helvetica-Bold" if key == "grand_total" else "Helvetica", 9)
        c.drawString(380, y, f"{label}:")
        c.drawRightString(W - 36, y, f[key])
        y -= 14

    c.setFont("Helvetica", 8)
    c.drawString(380, y - 30, f"For {f['supplier_name']}")
    c.drawString(380, y - 60, "Authorised Signatory")
    c.setFont("Helvetica-Oblique", 7)
    c.drawCentredString(W / 2, 24, SYNTHETIC_FOOTER)
    c.showPage()
    c.save()
    return t


def write_invoice(spec: InvoiceSpec, out_dir: Path, stem: str) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    pdf = out_dir / f"{stem}.pdf"
    truth = render_tally(spec, pdf)
    truth_path = out_dir / f"{stem}.truth.json"
    truth_path.write_text(json.dumps(truth, indent=2), encoding="utf-8")
    return pdf, truth_path

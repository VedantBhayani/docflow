"""Synthetic bank statements with ground truth (fictional bank, IFSC prefix ZZBK, fake VPAs).

As with invoices, one printed record per statement is both what gets drawn and the
truth file. Each line also carries the expected channel / reference / cheque number,
so Recon's matching keys are tested against known answers.
"""

import json
import random
from dataclasses import dataclass
from datetime import date, timedelta
from decimal import Decimal
from pathlib import Path

from reportlab.lib.pagesizes import A4
from reportlab.pdfbase.pdfmetrics import stringWidth
from reportlab.pdfgen import canvas

from docflow.synth.common import _FIRST, _SECOND, _SUFFIX, STATES, fmt_inr, make_party, money

BANK = "Zenith Co-operative Bank Ltd (SYNTHETIC)"
FOOTER = "SYNTHETIC TEST STATEMENT - generated by DocFlow, not a real bank statement"
W, H = A4
ROWS_PER_PAGE = 22
NARRATION_WIDTH = 188  # points; longer narrations wrap onto extra lines, as on real statements


@dataclass
class Txn:
    day: date
    narration: str
    ref_col: str  # Chq./Ref.No. column as printed
    debit: Decimal | None
    credit: Decimal | None
    channel: str
    ref_no: str | None  # reference that should be extracted from the narration
    cheque_no: str | None
    balance: Decimal = Decimal(0)


def _name(rng):
    return f"{rng.choice(_FIRST)} {rng.choice(_SECOND)} {rng.choice(_SUFFIX)}".upper()


def _txn(rng: random.Random, day: date, seq: int) -> Txn:
    kind = rng.choices(["UPI_CR", "UPI_DR", "IMPS", "NEFT_CR", "NEFT_DR", "RTGS", "CHQ", "CHG", "INT"], [4, 4, 2, 3, 3, 1, 2, 1, 1])[0]
    rrn = f"6{rng.randint(10**10, 10**11 - 1)}"
    utr = f"ZZBKN{day:%y%m%d}{rng.randint(0, 99999):05d}"
    rtgs = f"ZZBKRC{day:%Y%m%d}{rng.randint(0, 10**8 - 1):08d}"
    ifsc = f"ZZBK000{rng.randint(1000, 9999)}"
    who = _name(rng)
    amt = money(Decimal(rng.choice([rng.uniform(150, 5000), rng.uniform(5000, 90000), rng.uniform(90000, 900000)])))
    if kind == "UPI_CR":
        return Txn(day, f"UPI-{who[:18].strip()}-{who.split()[0].lower()}@okzz-{ifsc}-{rrn}-PAYMENT", rrn, None, amt, "UPI", rrn, None)
    if kind == "UPI_DR":
        return Txn(day, f"UPI-{who[:18].strip()}-{who.split()[0].lower()}@okzz-{ifsc}-{rrn}-PURCHASE", rrn, amt, None, "UPI", rrn, None)
    if kind == "IMPS":
        return Txn(day, f"IMPS-{rrn}-{who[:18].strip()}-ZENITH-XXXXXX{rng.randint(1000, 9999)}-ADVANCE", rrn, None, amt, "IMPS", rrn, None)
    if kind == "NEFT_CR":
        return Txn(day, f"NEFT CR-{ifsc}-{who[:20].strip()}-{utr}", utr, None, amt, "NEFT", utr, None)
    if kind == "NEFT_DR":
        return Txn(day, f"NEFT DR-{ifsc}-{who[:20].strip()}-{utr}-VENDOR", utr, amt, None, "NEFT", utr, None)
    if kind == "RTGS":
        return Txn(day, f"RTGS CR-{ifsc}-{who[:18].strip()}-{rtgs}", rtgs, None, money(amt * 10), "RTGS", rtgs, None)
    if kind == "CHQ":
        chq = f"{rng.randint(1, 999999):06d}"
        return Txn(day, f"CHQ PAID-MICR CTS-{who[:22].strip()}", chq, amt, None, "CHEQUE", None, chq)
    if kind == "CHG":
        return Txn(day, "SMS CHGS QTR", "", money(Decimal("17.70")), None, "CHARGE", None, None)
    return Txn(day, f"CREDIT INTEREST TILL {day:%d-%b-%Y}".upper(), "", None, money(Decimal(rng.uniform(40, 900))), "INTEREST", None, None)


def build_statement(rng: random.Random, n_txns: int, month_start: date) -> dict:
    holder = make_party(rng, rng.choice(list(STATES)))
    opening = money(Decimal(rng.uniform(50000, 2500000)))
    days = sorted(month_start + timedelta(days=rng.randint(0, 27)) for _ in range(n_txns))
    txns = [_txn(rng, d, i) for i, d in enumerate(days)]
    bal = opening
    for t in txns:
        bal = bal - (t.debit or 0) + (t.credit or 0)
        t.balance = bal
    period_end = month_start + timedelta(days=29)
    return {"holder": holder, "account": f"{rng.randint(10**13, 10**14 - 1)}", "opening": opening, "closing": bal,
            "from": month_start, "to": period_end, "txns": txns}


def printed_statement(st: dict, layout: str = "dash") -> dict:
    lines = []
    for t in st["txns"]:
        lines.append({
            "txn_date": t.day.strftime("%d/%m/%y"), "narration": t.narration, "ref_col": t.ref_col or None,
            "value_date": t.day.strftime("%d/%m/%y"),
            "debit": fmt_inr(t.debit) if t.debit is not None else None,
            "credit": fmt_inr(t.credit) if t.credit is not None else None,
            "balance": fmt_inr(t.balance),
        })
    return {
        "kind": "statement", "template": layout,
        "fields": {
            "bank_name": BANK, "account_number": st["account"], "account_holder": st["holder"].name,
            "period_from": st["from"].strftime("%d/%m/%Y"), "period_to": st["to"].strftime("%d/%m/%Y"),
            "opening_balance": fmt_inr(st["opening"]), "closing_balance": fmt_inr(st["closing"]),
        },
        "lines": lines,
        "derived": [{"channel": t.channel, "ref_no": t.ref_no, "cheque_no": t.cheque_no,
                     "direction": "DR" if t.debit is not None else "CR", "amount": str(t.debit if t.debit is not None else t.credit)}
                    for t in st["txns"]],
        "expected_flags": [], "acceptable_flags": [],
    }


def _wrap(text: str, width: float, font: str = "Helvetica", size: float = 6.6) -> list[str]:
    """Break a narration into lines that fit the column; break after '-' or '/' where possible."""
    lines, cur = [], ""
    for ch in text:
        if stringWidth(cur + ch, font, size) > width:
            cut = max(cur.rfind("-"), cur.rfind("/"), cur.rfind(" "))
            if cut > len(cur) // 2:
                lines.append(cur[: cut + 1])
                cur = cur[cut + 1 :] + ch
            else:
                lines.append(cur)
                cur = ch
        else:
            cur += ch
    return lines + ([cur] if cur else [])


def render_dash(rec: dict, path: Path, carry_forward: bool = True) -> None:
    """HDFC-like: Date | Narration | Chq./Ref.No. | Value Dt | Withdrawal Amt. | Deposit Amt. | Closing Balance."""
    f, lines = rec["fields"], rec["lines"]
    c = canvas.Canvas(str(path), pagesize=A4, invariant=1)
    c.setTitle("Statement of Account (SYNTHETIC)")
    cols = [("Date", 30, "l"), ("Narration", 70, "l"), ("Chq./Ref.No.", 266, "l"), ("Value Dt", 360, "l"),
            ("Withdrawal Amt.", 458, "r"), ("Deposit Amt.", 516, "r"), ("Closing Balance", 578, "r")]
    keys = ["txn_date", "narration", "ref_col", "value_date", "debit", "credit", "balance"]
    pages = [lines[i : i + ROWS_PER_PAGE] for i in range(0, len(lines), ROWS_PER_PAGE)] or [[]]
    prev_balance = f["opening_balance"]
    for p_i, chunk in enumerate(pages):
        c.setFont("Helvetica-Bold", 12)
        c.drawString(30, H - 40, f["bank_name"])
        c.setFont("Helvetica", 8)
        c.drawString(30, H - 56, f"Statement of Account   Account No: {f['account_number']}")
        c.drawString(30, H - 68, f"Account Holder: {f['account_holder']}")
        c.drawString(30, H - 80, f"Statement From : {f['period_from']} To : {f['period_to']}")
        c.drawRightString(W - 18, H - 56, f"Page {p_i + 1} of {len(pages)}")
        y = H - 105
        c.setFont("Helvetica-Bold", 7)
        for name, x, align in cols:
            (c.drawRightString if align == "r" else c.drawString)(x, y, name)
        c.line(28, y - 4, W - 16, y - 4)
        c.setFont("Helvetica", 6.6)
        if carry_forward and p_i > 0:
            y -= 13
            c.drawString(72, y, "BALANCE B/F")
            c.drawRightString(578, y, prev_balance)
        for ln in chunk:
            y -= 13
            wrapped = _wrap(ln["narration"], NARRATION_WIDTH)
            for (name, x, align), k in zip(cols, keys):
                v = wrapped[0] if k == "narration" else ln[k]
                if v:
                    (c.drawRightString if align == "r" else c.drawString)(x, y, v)
            for extra in wrapped[1:]:
                y -= 9
                c.drawString(70, y, extra)
            prev_balance = ln["balance"]
        if p_i == len(pages) - 1:
            y -= 30
            c.setFont("Helvetica-Bold", 7.5)
            c.drawString(30, y, "STATEMENT SUMMARY")
            c.setFont("Helvetica", 7.5)
            dr = sum(1 for ln in lines if ln["debit"])
            cr = sum(1 for ln in lines if ln["credit"])
            labels = [("Opening Balance", f["opening_balance"]), ("Dr Count", str(dr)), ("Cr Count", str(cr)),
                      ("Closing Bal", f["closing_balance"])]
            for i, (label, val) in enumerate(labels):
                c.drawString(30 + i * 130, y - 14, label)
                c.drawString(30 + i * 130, y - 26, val)
        c.setFont("Helvetica-Oblique", 6.5)
        c.drawCentredString(W / 2, 20, FOOTER)
        c.showPage()
    c.save()


def write_statement(rng: random.Random, out_dir: Path, stem: str, n_txns: int = 30, month_start: date = date(2026, 9, 1),
                    break_chain_at: int | None = None) -> tuple[Path, Path]:
    st = build_statement(rng, n_txns, month_start)
    rec = printed_statement(st)
    if break_chain_at is not None:
        # Printed balance off by Rs 1,000 on one row; later balances continue from the true value.
        ln = rec["lines"][break_chain_at]
        from docflow.parse import parse_amount

        ln["balance"] = fmt_inr(parse_amount(ln["balance"]) + Decimal(1000))
        rec["expected_flags"] = ["S1"]
        rec["broken_line"] = break_chain_at
    out_dir.mkdir(parents=True, exist_ok=True)
    pdf = out_dir / f"{stem}.pdf"
    render_dash(rec, pdf)
    truth = out_dir / f"{stem}.truth.json"
    truth.write_text(json.dumps(rec, indent=2), encoding="utf-8")
    return pdf, truth

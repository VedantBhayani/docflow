LINE_KEYS = ["description", "hsn", "qty", "uqc", "unit_price", "taxable_value", "gst_rate", "cgst", "sgst", "igst"]


def _qr_image(token: str) -> ImageReader:
    img = qrcode.make(token, error_correction=qrcode.constants.ERROR_CORRECT_M, box_size=4, border=2)
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    buf.seek(0)
    return ImageReader(buf)


def _qr_block(c: canvas.Canvas, rec: dict, x: float, y: float, size: float = 110) -> None:
    if not rec["qr"]:
        return
    c.drawImage(_qr_image(rec["qr"]["token"]), x, y, size, size)
    c.setFont("Helvetica", 6.5)
    c.drawString(36, 806, f"IRN: {rec['qr']['irn_printed']}")
    c.drawString(36, 797, f"Ack No.: {rec['qr']['ack_no']}   Ack Date: {rec['qr']['ack_date']}")
    c.setFont("Helvetica-Bold", 6.5)
    c.drawString(36, 788, QR_BANNER)


def _table(c: canvas.Canvas, lines: list[dict], y: float, cols=COLS, header_font=("Helvetica-Bold", 7.5)) -> float:
    c.setFont(*header_font)
    for name, x in cols:
        c.drawString(x, y, name)
    c.line(36, y - 4, W - 30, y - 4)
    c.setFont("Helvetica", 7.5)
    for i, ln in enumerate(lines, 1):
        y -= 16
        for (_, x), v in zip(cols, [str(i)] + [ln[k] for k in LINE_KEYS]):
            if v is not None:
                c.drawString(x, y, v)
    c.line(36, y - 6, W - 30, y - 6)
    return y


def _footer(c: canvas.Canvas, rec: dict, y: float) -> None:
    if rec["notes"]:
        c.setFont("Helvetica", 7.5)
        c.drawString(36, y, rec["notes"])
    c.setFont("Helvetica-Oblique", 7)
    c.drawCentredString(W / 2, 24, SYNTHETIC_FOOTER)



"""Synthetic bank statements with ground truth (fictional bank, IFSC prefix ZZBK, fake VPAs).

Four layouts modelled on research note 04, each testing something different:
  dash   HDFC-like   Date | Narration | Chq./Ref.No. | Value Dt | Withdrawal | Deposit | Closing Balance
  slash  SBI-like    Txn Date | Value Date | Description | Ref No./Cheque No. | CREDIT | DEBIT | Balance  ("-" when empty)
  mmt    ICICI-like  Date | Mode | Particulars | DEPOSITS | WITHDRAWALS | Balance  (B/F rows, page Total rows)
  kotak  Kotak-like  # | Date | Description | Chq/Ref. No. | Withdrawal (Dr.) | Deposit (Cr.) | Balance  ("02 Sep 2026")
One printed record per statement is both what gets drawn and the truth file. Each line also
carries the expected channel / reference / cheque number, so Recon's matching keys are tested.
"""

import json
import random
from dataclasses import dataclass, field
from datetime import date, datetime, timedelta
from decimal import Decimal
from pathlib import Path

from reportlab.lib.pagesizes import A4
from reportlab.pdfbase.pdfmetrics import stringWidth
from reportlab.pdfgen import canvas

from docflow.parse import parse_amount
from docflow.synth.common import _FIRST, _SECOND, _SUFFIX, STATES, fmt_inr, make_party, money

BANK = "Zenith Co-operative Bank Ltd (SYNTHETIC)"
FOOTER = "SYNTHETIC TEST STATEMENT - generated by DocFlow, not a real bank statement"
W, H = A4
ROWS_PER_PAGE = 22
LAYOUTS = ("dash", "slash", "mmt", "kotak")
STATEMENT_DEFECTS = ("broken_chain", "closing_mismatch", "both_dr_cr", "date_outside_period")


@dataclass
class Txn:
    day: date
    narration: str
    ref_col: str | None  # reference column as printed (None = blank, or the layout has no such column)
    debit: Decimal | None
    credit: Decimal | None
    channel: str
    ref_no: str | None  # reference that should be extracted from the narration
    cheque_no: str | None
    mode: str = ""
    balance: Decimal = Decimal(0)


@dataclass
class Layout:
    name: str
    columns: list[tuple[str, str, float, str]]  # (header, key, x, align)
    date_fmt: str
    empty: str | None  # what an empty amount/ref cell prints; None = blank
    narration_width: float
    extras: dict = field(default_factory=dict)


LAYOUT_SPECS = {
    "dash": Layout("dash", [("Date", "txn_date", 30, "l"), ("Narration", "narration", 70, "l"), ("Chq./Ref.No.", "ref_col", 266, "l"),
                            ("Value Dt", "value_date", 360, "l"), ("Withdrawal Amt.", "debit", 458, "r"), ("Deposit Amt.", "credit", 516, "r"),
                            ("Closing Balance", "balance", 578, "r")], "%d/%m/%y", None, 188),
    "slash": Layout("slash", [("Txn Date", "txn_date", 26, "l"), ("Value Date", "value_date", 72, "l"), ("Description", "narration", 118, "l"),
                              ("Ref No./Cheque No.", "ref_col", 300, "l"), ("Credit", "credit", 440, "r"), ("Debit", "debit", 505, "r"),
                              ("Balance", "balance", 578, "r")], "%d/%m/%Y", "-", 175),
    "mmt": Layout("mmt", [("Date", "txn_date", 30, "l"), ("Mode", "mode", 80, "l"), ("Particulars", "narration", 122, "l"),
                          ("Deposits", "credit", 430, "r"), ("Withdrawals", "debit", 500, "r"), ("Balance", "balance", 578, "r")], "%d-%m-%Y", None, 240),
    "kotak": Layout("kotak", [("#", "seq", 26, "l"), ("Date", "txn_date", 44, "l"), ("Description", "narration", 100, "l"),
                              ("Chq/Ref. No.", "ref_col", 300, "l"), ("Withdrawal (Dr.)", "debit", 450, "r"), ("Deposit (Cr.)", "credit", 515, "r"),
                              ("Balance", "balance", 578, "r")], "%d %b %Y", "-", 190),
}


def _name(rng):
    return f"{rng.choice(_FIRST)} {rng.choice(_SECOND)} {rng.choice(_SUFFIX)}".upper()


def _txn(rng: random.Random, day: date, layout: str) -> Txn:
    kind = rng.choices(["UPI_CR", "UPI_DR", "IMPS", "NEFT_CR", "NEFT_DR", "RTGS", "CHQ", "CHG", "INT"], [4, 4, 2, 3, 3, 1, 2, 1, 1])[0]
    rrn = f"6{rng.randint(10**10, 10**11 - 1)}"
    utr = f"ZZBKN{day:%y%m%d}{rng.randint(0, 99999):05d}"
    rtgs = f"ZZBKRC{day:%Y%m%d}{rng.randint(0, 10**8 - 1):08d}"
    ifsc = f"ZZBK000{rng.randint(1000, 9999)}"
    who = _name(rng)
    short = who[:18].strip()
    vpa = f"{who.split()[0].lower()}@okzz"
    amt = money(Decimal(rng.choice([rng.uniform(150, 5000), rng.uniform(5000, 90000), rng.uniform(90000, 900000)])))
    chq = f"{rng.randint(1, 999999):06d}"
    bank_id = f"ZZ{rng.randint(10**7, 10**8 - 1)}"
    # Per layout: kind -> (narration, ref column as printed, reference expected from the narration)
    T = {
        "dash": {
            "UPI_CR": (f"UPI-{short}-{vpa}-{ifsc}-{rrn}-PAYMENT", rrn, rrn), "UPI_DR": (f"UPI-{short}-{vpa}-{ifsc}-{rrn}-PURCHASE", rrn, rrn),
            "IMPS": (f"IMPS-{rrn}-{short}-ZENITH-XXXXXX{rng.randint(1000, 9999)}-ADVANCE", rrn, rrn),
            "NEFT_CR": (f"NEFT CR-{ifsc}-{who[:20].strip()}-{utr}", utr, utr), "NEFT_DR": (f"NEFT DR-{ifsc}-{who[:20].strip()}-{utr}-VENDOR", utr, utr),
            "RTGS": (f"RTGS CR-{ifsc}-{short}-{rtgs}", rtgs, rtgs), "CHQ": (f"CHQ PAID-MICR CTS-{who[:22].strip()}", chq, None),
            "CHG": ("SMS CHGS QTR", None, None), "INT": (f"CREDIT INTEREST TILL {day:%d-%b-%Y}".upper(), None, None)},
        "slash": {
            "UPI_CR": (f"DEP TFR UPI/CR/{rrn}/{short}/ZZBK/{vpa}/PAYMENT", rrn, rrn), "UPI_DR": (f"WDL TFR UPI/DR/{rrn}/{short}/ZZBK/{vpa}/PURCHASE", rrn, rrn),
            "IMPS": (f"IMPS/{rrn}/ZENITH-XXXX{rng.randint(1000, 9999)}-{short}/ADVANCE", rrn, rrn),
            "NEFT_CR": (f"NEFT*{ifsc}*{utr}*{short}", utr, utr), "NEFT_DR": (f"NEFT*{ifsc}*{utr}*{short}", utr, utr),
            "RTGS": (f"RTGS/{rtgs}/ZENITH/{short}", rtgs, rtgs), "CHQ": (f"TO CHQ PAID {who[:20].strip()}", chq, None),
            "CHG": ("SMS CHARGES", None, None), "INT": ("CREDIT INTEREST", None, None)},
        "mmt": {
            "UPI_CR": (f"UPI/{short}/{vpa}/PAYMENT/ZENITH/{rrn}/ICI{rng.randint(10**8, 10**9 - 1)}", None, rrn),
            "UPI_DR": (f"UPI/{short}/{vpa}/PURCHASE/ZENITH/{rrn}/ICI{rng.randint(10**8, 10**9 - 1)}", None, rrn),
            "IMPS": (f"MMT/IMPS/{rrn}/ADVANCE/{short}/ZENITH", None, rrn),
            "NEFT_CR": (f"NEFT-{utr}-{short}-INVOICE-XXXX{rng.randint(1000, 9999)}-{ifsc}", None, utr),
            "NEFT_DR": (f"BIL/NEFT/{bank_id}/VENDOR/{short}/ZENITH", None, None),  # bank's own transfer id, not a UTR
            "RTGS": (f"RTGS/{rtgs}/ZENITH/{short}", None, rtgs), "CHQ": (f"CLG/{short}/{chq}/ZZBK/{day:%d.%m.%Y}", None, None),
            "CHG": ("SMS CHGS", None, None), "INT": ("CREDIT INTEREST", None, None)},
        "kotak": {
            "UPI_CR": (f"UPI/{short}/{rrn}/PAYMENT", f"UPI-{rng.randint(10**11, 10**12 - 1)}", rrn),
            "UPI_DR": (f"UPI/{short}/{rrn}/PURCHASE", f"UPI-{rng.randint(10**11, 10**12 - 1)}", rrn),
            "IMPS": (f"IMPS-{rrn}-{short}", f"IMPS-{rrn}", rrn), "NEFT_CR": (f"NEFT {utr} {short}", utr, utr),
            "NEFT_DR": (f"NEFT {utr} {short}", utr, utr), "RTGS": (f"RTGS {rtgs} {short}", rtgs, rtgs),
            "CHQ": (f"CHQ PAID {who[:20].strip()}", chq, None), "CHG": ("SMS CHGS", None, None),
            "INT": (f"Int.Pd:{rng.randint(10**6, 10**7 - 1)}:{day:%d-%m-%Y}", None, None)},
    }
    narration, ref_col, ref_no = T[layout][kind]
    debit = amt if kind in ("UPI_DR", "NEFT_DR", "CHQ") else None
    credit = None if debit is not None else amt
    if kind == "CHG":
        debit, credit = money(Decimal("17.70")), None
    if kind == "INT":
        credit = money(Decimal(rng.uniform(40, 900)))
    if kind == "RTGS":
        credit = money(amt * 10)
    channel = {"UPI_CR": "UPI", "UPI_DR": "UPI", "IMPS": "IMPS", "NEFT_CR": "NEFT", "NEFT_DR": "NEFT", "RTGS": "RTGS",
               "CHQ": "CHEQUE", "CHG": "CHARGE", "INT": "INTEREST"}[kind]
    mode = {"UPI": "UPI", "IMPS": "IMPS", "NEFT": "NEFT", "RTGS": "RTGS", "CHEQUE": "CLG", "CHARGE": "CHG", "INTEREST": "INT"}[channel]
    return Txn(day, narration, ref_col, debit, credit, channel, ref_no, chq if kind == "CHQ" else None, mode)


def build_statement(rng: random.Random, n_txns: int, month_start: date, layout: str = "dash") -> dict:
    holder = make_party(rng, rng.choice(list(STATES)))
    opening = money(Decimal(rng.uniform(50000, 2500000)))
    days = sorted(month_start + timedelta(days=rng.randint(0, 27)) for _ in range(n_txns))
    txns = [_txn(rng, d, layout) for d in days]
    bal = opening
    for t in txns:
        bal = bal - (t.debit or 0) + (t.credit or 0)
        t.balance = bal
    return {"holder": holder, "account": f"{rng.randint(10**13, 10**14 - 1)}", "opening": opening, "closing": bal,
            "from": month_start, "to": month_start + timedelta(days=29), "txns": txns}


def _has(layout: Layout, key: str) -> bool:
    return any(k == key for _, k, _, _ in layout.columns)


def printed_statement(st: dict, layout: str = "dash") -> dict:
    L = LAYOUT_SPECS[layout]
    lines = []
    for t in st["txns"]:
        ln = {"txn_date": t.day.strftime(L.date_fmt), "narration": t.narration}
        if _has(L, "ref_col"):
            ln["ref_col"] = t.ref_col
        if _has(L, "value_date"):
            ln["value_date"] = t.day.strftime(L.date_fmt)
        ln.update({"debit": fmt_inr(t.debit) if t.debit is not None else None,
                   "credit": fmt_inr(t.credit) if t.credit is not None else None, "balance": fmt_inr(t.balance)})
        lines.append(ln)
    return {
        "kind": "statement", "template": layout,
        "fields": {
            "bank_name": BANK, "account_number": st["account"], "account_holder": st["holder"].name,
            "period_from": st["from"].strftime("%d/%m/%Y"), "period_to": st["to"].strftime("%d/%m/%Y"),
            "opening_balance": fmt_inr(st["opening"]), "closing_balance": fmt_inr(st["closing"]),
        },
        "lines": lines,
        "modes": [t.mode for t in st["txns"]],
        "derived": [{"channel": t.channel, "ref_no": t.ref_no, "cheque_no": t.cheque_no,
                     "direction": "DR" if t.debit is not None else "CR", "amount": str(t.debit if t.debit is not None else t.credit)}
                    for t in st["txns"]],
        "defect": None, "expected_flags": [], "acceptable_flags": [],
    }


def _wrap(text: str, width: float, font: str = "Helvetica", size: float = 6.6) -> list[str]:
    """Break a narration into lines that fit the column; break after '-', '/' or a space where possible."""
    lines, cur = [], ""
    for ch in text:
        if stringWidth(cur + ch, font, size) > width:
            cut = max(cur.rfind("-"), cur.rfind("/"), cur.rfind(" "))
            if cut > len(cur) // 2:
                lines.append(cur[: cut + 1])
                cur = cur[cut + 1 :] + ch
            else:
                lines.append(cur)
                cur = ch
        else:
            cur += ch
    return lines + ([cur] if cur else [])


def render_statement(rec: dict, path: Path) -> None:
    L = LAYOUT_SPECS[rec["template"]]
    f, lines = rec["fields"], rec["lines"]
    c = canvas.Canvas(str(path), pagesize=A4, invariant=1)
    c.setTitle("Statement of Account (SYNTHETIC)")
    pages = [list(range(i, min(i + ROWS_PER_PAGE, len(lines)))) for i in range(0, len(lines), ROWS_PER_PAGE)] or [[]]
    prev_balance = f["opening_balance"]
    col_x = {k: x for _, k, x, _ in L.columns}

    for p_i, idx in enumerate(pages):
        c.setFont("Helvetica-Bold", 12)
        c.drawString(28, H - 40, f["bank_name"])
        c.setFont("Helvetica", 8)
        c.drawString(28, H - 56, f"Account No: {f['account_number']}")
        c.drawString(28, H - 68, f"Account Holder: {f['account_holder']}")
        if L.name == "slash":
            c.drawString(28, H - 80, f"Statement From : {f['period_from']} to {f['period_to']}")
            if p_i == 0:
                c.drawRightString(W - 18, H - 68, f"Balance as on {f['period_from']} : {f['opening_balance']}")
        elif L.name == "mmt":
            c.drawString(28, H - 80, f"Statement period: {f['period_from']} - {f['period_to']}")
            if p_i == 0:
                c.drawRightString(W - 18, H - 68, f"Opening Balance : {f['opening_balance']}")
        else:
            c.drawString(28, H - 80, f"Statement From : {f['period_from']} To : {f['period_to']}")
        c.drawRightString(W - 18, H - 56, f"Page {p_i + 1} of {len(pages)}")
        y = H - 105
        c.setFont("Helvetica-Bold", 7)
        for header, _, x, align in L.columns:
            (c.drawRightString if align == "r" else c.drawString)(x, y, header)
        c.line(24, y - 4, W - 16, y - 4)
        c.setFont("Helvetica", 6.6)
        narr_x = col_x["narration"]
        if (L.name == "dash" and p_i > 0) or L.name == "mmt":
            y -= 13
            c.drawString(narr_x, y, "BALANCE B/F" if L.name == "dash" else "B/F")
            c.drawRightString(578, y, prev_balance)
        if L.name == "kotak" and p_i == 0:
            y -= 13
            c.drawString(narr_x, y, "Opening Balance")
            c.drawRightString(578, y, f["opening_balance"])
        page_dr = page_cr = Decimal(0)
        for i in idx:
            ln = lines[i]
            y -= 13
            wrapped = _wrap(ln["narration"], L.narration_width)
            for _, key, x, align in L.columns:
                if key == "narration":
                    v = wrapped[0]
                elif key == "seq":
                    v = str(i + 1)
                elif key == "mode":
                    v = rec["modes"][i]
                elif key in ("debit", "credit", "ref_col"):
                    v = ln.get(key) or L.empty
                else:
                    v = ln.get(key)
                if v:
                    (c.drawRightString if align == "r" else c.drawString)(x, y, v)
            for extra in wrapped[1:]:
                y -= 9
                c.drawString(narr_x, y, extra)
            page_dr += parse_amount(ln["debit"]) or 0
            page_cr += parse_amount(ln["credit"]) or 0
            prev_balance = ln["balance"]
        if L.name == "mmt":
            y -= 15
            c.setFont("Helvetica-Bold", 6.6)
            c.drawString(narr_x, y, "Total:")
            c.drawRightString(col_x["credit"], y, fmt_inr(page_cr))
            c.drawRightString(col_x["debit"], y, fmt_inr(page_dr))
            c.setFont("Helvetica", 6.6)
        if p_i == len(pages) - 1:
            y -= 30
            c.setFont("Helvetica-Bold", 7.5)
            c.drawString(28, y, {"dash": "STATEMENT SUMMARY", "slash": "Statement Summary", "mmt": "Account Summary", "kotak": "Account Summary"}[L.name])
            c.setFont("Helvetica", 7.5)
            dr = sum(1 for ln in lines if ln["debit"])
            cr = sum(1 for ln in lines if ln["credit"])
            closing_label = "Closing Bal" if L.name == "dash" else "Closing Balance"
            for k, (label, val) in enumerate([("Opening Balance", f["opening_balance"]), ("Dr Count", str(dr)), ("Cr Count", str(cr)),
                                              (closing_label, f["closing_balance"])]):
                c.drawString(28 + k * 130, y - 14, label)
                c.drawString(28 + k * 130, y - 26, val)
        c.setFont("Helvetica-Oblique", 6.5)
        c.drawCentredString(W / 2, 20, FOOTER)
        c.showPage()
    c.save()


def apply_statement_defect(rec: dict, defect: str, rng: random.Random) -> None:
    L = LAYOUT_SPECS[rec["template"]]
    n = len(rec["lines"])
    i = rng.randint(2, n - 3)
    ln = rec["lines"][i]
    if defect == "broken_chain":
        ln["balance"] = fmt_inr(parse_amount(ln["balance"]) + Decimal(1000))
        rec["expected_flags"], rec["defect_line"] = ["S1"], i
    elif defect == "closing_mismatch":
        rec["fields"]["closing_balance"] = fmt_inr(parse_amount(rec["fields"]["closing_balance"]) + Decimal(500))
        rec["expected_flags"] = ["S2"]
    elif defect == "both_dr_cr":
        # The row prints a debit AND a credit; balances from it onwards include both, so only S3 should fire.
        extra = money(parse_amount(ln["debit"] or ln["credit"]) / 4)
        if ln["debit"] is not None:
            ln["credit"], delta = fmt_inr(extra), extra
        else:
            ln["debit"], delta = fmt_inr(extra), -extra
        for j in range(i, n):
            rec["lines"][j]["balance"] = fmt_inr(parse_amount(rec["lines"][j]["balance"]) + delta)
        rec["fields"]["closing_balance"] = fmt_inr(parse_amount(rec["fields"]["closing_balance"]) + delta)
        rec["derived"][i]["direction"], rec["derived"][i]["amount"] = None, None
        rec["expected_flags"], rec["defect_line"] = ["S3"], i
    elif defect == "date_outside_period":
        late = datetime.strptime(rec["fields"]["period_to"], "%d/%m/%Y").date() + timedelta(days=3)
        ln["txn_date"] = late.strftime(L.date_fmt)
        if ln.get("value_date"):
            ln["value_date"] = late.strftime(L.date_fmt)
        rec["expected_flags"], rec["defect_line"] = ["S4"], i
    rec["defect"] = defect


def generate_statement_set(out_dir: Path, seed: int = 11) -> list[dict]:
    """30 statements: 4 layouts (8/8/7/7); 10 scanned (5 light, 5 heavy); 12 single-defect statements (3 of each type)."""
    from docflow.synth.scan import degrade

    rng = random.Random(seed)
    slots = [{"layout": lay, "scan": "digital", "defect": None, "split": "heldout"} for lay, n in zip(LAYOUTS, (8, 8, 7, 7)) for _ in range(n)]
    for k, s in enumerate(rng.sample(slots, 10)):
        s["scan"] = "light" if k < 5 else "heavy"
    for defect in STATEMENT_DEFECTS:
        for s in rng.sample([s for s in slots if s["scan"] == "digital" and s["defect"] is None], 3):
            s["defect"] = defect
    for defect in STATEMENT_DEFECTS:  # one of each defect type in dev
        rng.choice([s for s in slots if s["defect"] == defect])["split"] = "dev"
    for lay in LAYOUTS:
        clean = [s for s in slots if s["layout"] == lay and s["defect"] is None]
        for s in rng.sample(clean, round(len(clean) * 0.3)):
            s["split"] = "dev"
    out_dir.mkdir(parents=True, exist_ok=True)
    manifest = []
    for n, slot in enumerate(slots, 1):
        doc_id = f"stmt-{n:04d}"
        drng = random.Random(f"{seed}-{doc_id}")
        st = build_statement(drng, drng.randint(18, 50), date(2026, drng.randint(4, 9), 1), slot["layout"])
        rec = printed_statement(st, slot["layout"])
        if slot["defect"]:
            apply_statement_defect(rec, slot["defect"], drng)
        rec.update({"id": doc_id, "scan": slot["scan"], "split": slot["split"]})
        pdf = out_dir / f"{doc_id}.pdf"
        if slot["scan"] == "digital":
            render_statement(rec, pdf)
        else:
            src = out_dir / "_digital_sources" / f"{doc_id}.pdf"
            src.parent.mkdir(parents=True, exist_ok=True)
            render_statement(rec, src)
            rec["scan_meta"] = degrade(src, pdf, slot["scan"], seed=drng.randint(0, 2**31))
        (out_dir / f"{doc_id}.truth.json").write_text(json.dumps(rec, indent=2), encoding="utf-8")
        manifest.append({"id": doc_id, "template": slot["layout"], "scan": slot["scan"], "defect": rec["defect"], "split": slot["split"],
                         "expected_flags": rec["expected_flags"], "acceptable_flags": [], "qr": False,
                         "pages": (len(rec["lines"]) - 1) // ROWS_PER_PAGE + 1})
    (out_dir / "manifest.json").write_text(json.dumps({"seed": seed, "documents": manifest}, indent=2), encoding="utf-8")
    return manifest


def write_statement(rng: random.Random, out_dir: Path, stem: str, n_txns: int = 30, month_start: date = date(2026, 9, 1),
                    break_chain_at: int | None = None, layout: str = "dash") -> tuple[Path, Path]:
    """Single statement (used by the tracer)."""
    st = build_statement(rng, n_txns, month_start, layout)
    rec = printed_statement(st, layout)
    if break_chain_at is not None:
        ln = rec["lines"][break_chain_at]
        ln["balance"] = fmt_inr(parse_amount(ln["balance"]) + Decimal(1000))
        rec["expected_flags"] = ["S1"]
        rec["broken_line"] = break_chain_at
    out_dir.mkdir(parents=True, exist_ok=True)
    pdf = out_dir / f"{stem}.pdf"
    render_statement(rec, pdf)
    truth = out_dir / f"{stem}.truth.json"
    truth.write_text(json.dumps(rec, indent=2), encoding="utf-8")
    return pdf, truth

SIDED = {"signed"}  # layouts whose balances carry a Dr/Cr side instead of a minus sign


def fmt_balance(layout: str, x: Decimal) -> str:
    if layout in SIDED:
        return f"{fmt_inr(abs(x))} {'Dr' if x < 0 else 'Cr'}"
    return fmt_inr(x)


def _name(rng):
    return f"{rng.choice(_FIRST)} {rng.choice(_SECOND)} {rng.choice(_SUFFIX)}".upper()



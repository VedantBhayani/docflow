def render(rec: dict, spec: InvoiceSpec, path: Path) -> None:
    c = canvas.Canvas(str(path), pagesize=A4, invariant=1)  # byte-deterministic output
    c.setTitle(f"Tax Invoice {rec['fields']['invoice_no']} (SYNTHETIC)")
    RENDERERS[rec["template"]](c, rec, spec)
    c.showPage()
    c.save()


# ---------------------------------------------------------------- defects

def _ensure_goods_first_line(spec: InvoiceSpec, rng: random.Random) -> None:
    if spec.lines[0].hsn.startswith("99"):
        desc, hsn, uqc, price = rng.choice([c for c in CATALOGUE if not c[1].startswith("99")])
        spec.lines[0] = Line(desc, hsn, Decimal(rng.choice([2, 5, 10])), uqc, money(Decimal(price)), Decimal(18))


def apply_spec_defect(spec: InvoiceSpec, defect: str, rng: random.Random) -> list[str]:
    """Defects that change the underlying invoice. Returns expected blocking flag IDs."""
    if defect == "wrong_tax_type":
        spec.tax_mode = "cgst" if not spec.intra_state else "igst"
        spec.compute()
        return ["C2"] if spec.intra_state else ["C3"]
    if defect == "invalid_slab":
        _ensure_goods_first_line(spec, rng)
        spec.lines[0].gst_rate = Decimal(12)  # 12% abolished for goods from 22.09.2025
        spec.compute()
        return ["C7"]
    return []


def apply_printed_defect(rec: dict, spec: InvoiceSpec, defect: str) -> list[str]:
    """Defects applied to what is printed. Returns expected blocking flag IDs."""
    f = rec["fields"]
    if defect == "bad_gstin_checksum":
        last = f["supplier_gstin"][-1]
        f["supplier_gstin"] = f["supplier_gstin"][:-1] + ("7" if last != "7" else "8")
        return ["G5"]
    if defect == "line_math":
        ln = spec.lines[0]
        delta = max(Decimal("25.00"), money((ln.cgst + ln.sgst + ln.igst) * Decimal("0.03")))
        if spec.intra_state:
            half = money(delta / 2)
            ln.cgst += half
            ln.sgst += half
        else:
            ln.igst += delta
        # Totals stay consistent with the (wrong) line, so only the line-level check should fire.
        spec.cgst_total = sum((x.cgst for x in spec.lines), Decimal(0))
        spec.sgst_total = sum((x.sgst for x in spec.lines), Decimal(0))
        spec.igst_total = sum((x.igst for x in spec.lines), Decimal(0))
        pre = spec.taxable_total + spec.cgst_total + spec.sgst_total + spec.igst_total
        spec.grand_total = pre.quantize(Decimal("1"), rounding=ROUND_HALF_UP).quantize(Decimal("0.01"))
        spec.round_off = spec.grand_total - pre
        fresh = printed_record(spec, rec["template"])
        rec["fields"], rec["lines"] = fresh["fields"], fresh["lines"]
        return ["C6"]
    if defect == "missing_recipient_gstin":
        f["recipient_gstin"] = None
        return ["A5", "E2"]
    if defect == "prompt_injection":
        rec["notes"] = INJECTION
        return []
    return []



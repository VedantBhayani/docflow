def _plan(rng: random.Random) -> list[dict]:
    """120 invoices: 4 templates x 30. 60 digital / 32 light / 28 heavy. 48 with QR (40%). 31 defect documents."""
    slots = []
    for template in TEMPLATES:
        for k in range(30):
            scan = "digital" if k < 15 else ("light" if k < 23 else "heavy")
            slots.append({"template": template, "scan": scan, "qr": template == "einvoice", "defect": None, "group": None})
    for template in ("tally", "zoho", "word"):  # 18 more QR documents, digital and scanned alike
        for s in [s for s in slots if s["template"] == template][::5][:6]:
            s["qr"] = True

    def take(pred, n, defect):
        free = [s for s in slots if s["defect"] is None and pred(s)]
        for s in rng.sample(free, n):
            s["defect"] = defect

    # Defects sit mostly on digital pages, so the defect is the only difficulty in that document.
    for d in ("bad_gstin_checksum", "wrong_tax_type", "line_math", "invalid_slab", "missing_recipient_gstin", "prompt_injection"):
        take(lambda s: s["scan"] == "digital", 3, d)
    take(lambda s: s["scan"] == "digital" and s["qr"], 3, "qr_total_mismatch")
    take(lambda s: s["scan"] == "digital" and s["qr"], 3, "qr_bad_signature")
    take(lambda s: s["scan"] == "light", 3, "rotated_page")
    take(lambda s: s["scan"] == "digital", 4, "duplicate_invoice_no")
    for i, s in enumerate([s for s in slots if s["defect"] == "duplicate_invoice_no"]):
        s["group"] = f"dup{i // 2}"
    return slots


def _split(slots: list[dict], rng: random.Random) -> None:
    """30% dev / 70% held-out, stratified by defect type and template; duplicate pairs stay together."""
    for s in slots:
        s["split"] = "heldout"
    for defect in DEFECTS:
        members = [s for s in slots if s["defect"] == defect]
        if defect == "duplicate_invoice_no":
            dev_group = rng.choice(sorted({s["group"] for s in members}))
            for s in members:
                if s["group"] == dev_group:
                    s["split"] = "dev"
        else:
            rng.choice(members)["split"] = "dev"
    for template in TEMPLATES:
        clean = [s for s in slots if s["defect"] is None and s["template"] == template]
        for s in rng.sample(clean, round(len(clean) * 0.3)):
            s["split"] = "dev"


def generate_invoice_set(out_dir: Path, seed: int = 7) -> list[dict]:
    from docflow.synth.scan import degrade

    rng = random.Random(seed)
    slots = _plan(rng)
    _split(slots, rng)
    out_dir.mkdir(parents=True, exist_ok=True)
    digital_dir = out_dir / "_digital_sources"
    manifest = []
    dup_first: dict[str, InvoiceSpec] = {}
    for n, slot in enumerate(slots, 1):
        doc_id = f"inv-{n:04d}"
        drng = random.Random(f"{seed}-{doc_id}")
        defect = slot["defect"]
        if defect == "duplicate_invoice_no" and slot["group"] in dup_first:
            first = dup_first[slot["group"]]
            spec = build_spec(drng, 0, invoice_date=first.invoice_date + timedelta(days=drng.randint(1, 20)), supplier=first.supplier)
            spec.invoice_no = first.invoice_no
        else:
            spec = build_spec(drng, n)
            if defect == "duplicate_invoice_no":
                dup_first[slot["group"]] = spec
        expected = apply_spec_defect(spec, defect, drng) if defect else []
        rec = printed_record(spec, slot["template"])
        if defect:
            expected += apply_printed_defect(rec, spec, defect)
        if defect == "duplicate_invoice_no":
            expected = ["A3"]
        if slot["qr"]:
            payload = qr_payload(spec, drng)
            if defect == "qr_total_mismatch":
                payload["TotInvVal"] = float(spec.grand_total + Decimal(1000))
                expected = ["Q2"]
            token = sign_payload(payload, rogue=defect == "qr_bad_signature")
            if defect == "qr_bad_signature":
                expected = ["Q1"]
            rec["qr"] = {"token": token, "payload": payload, "irn_printed": payload["Irn"],
                         "ack_no": f"11{drng.randint(10**12, 10**13 - 1)}", "ack_date": payload["IrnDt"][:10]}
            rec["fields"]["irn"] = payload["Irn"]
        rec.update({"id": doc_id, "scan": slot["scan"], "defect": defect, "split": slot["split"],
                    "expected_flags": sorted(set(expected)), "acceptable_flags": ["P1"] if defect == "rotated_page" else []})

        pdf = out_dir / f"{doc_id}.pdf"
        if slot["scan"] == "digital":
            render(rec, spec, pdf)
        else:
            src = digital_dir / f"{doc_id}.pdf"
            src.parent.mkdir(parents=True, exist_ok=True)
            render(rec, spec, src)
            rec["scan_meta"] = degrade(src, pdf, slot["scan"], seed=drng.randint(0, 2**31), rotate90=defect == "rotated_page")
        (out_dir / f"{doc_id}.truth.json").write_text(json.dumps(rec, indent=2), encoding="utf-8")
        manifest.append({k: rec[k] for k in ("id", "template", "scan", "defect", "split", "expected_flags", "acceptable_flags")} | {"qr": bool(rec["qr"])})
    (out_dir / "manifest.json").write_text(json.dumps({"seed": seed, "documents": manifest}, indent=2), encoding="utf-8")
    return manifest


def write_invoice(spec: InvoiceSpec, out_dir: Path, stem: str, template: str = "tally") -> tuple[Path, Path]:
    """Single clean invoice (used by the tracer)."""
    out_dir.mkdir(parents=True, exist_ok=True)
    rec = printed_record(spec, template)
    pdf = out_dir / f"{stem}.pdf"
    render(rec, spec, pdf)
    truth_path = out_dir / f"{stem}.truth.json"
    truth_path.write_text(json.dumps(rec, indent=2), encoding="utf-8")
    return pdf, truth_path
